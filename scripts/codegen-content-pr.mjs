#!/usr/bin/env node
/**
 * Regenerates the hiscores content and opens a draft PR with it. A human verifies
 * the spelling and merges — this never merges, publishes, or touches main.
 *
 *   node scripts/codegen-content-pr.mjs         update, gate, draft PR
 *   node scripts/codegen-content-pr.mjs --dry   show the diff, change no git state
 *
 * Requires `pnpm build` first, and an authenticated `gh` (GH_TOKEN in CI).
 */
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { keyOf, regen } from './regen-content.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const run = (file, args) =>
  execFileSync(file, args, { cwd: root, stdio: 'inherit' });
const read = (file, args) =>
  execFileSync(file, args, { cwd: root, encoding: 'utf8' });
const bin = (name) => `${root}node_modules/.bin/${name}`;

/** The only paths codegen is allowed to change in a PR. */
const GENERATED_FILES = ['src/utils/generated', 'README.md'];

/**
 * Same gate CI runs, so a red PR is never filed.
 *
 * ponytail: mirrors main.yml's tool list by hand; add lint:check/format:check
 * scripts to package.json if a third caller ever needs the same list.
 */
const GATE = [
  [bin('prettier'), ['--check', '{src,__tests__}/**/*.ts', 'README.md']],
  [bin('eslint'), ['{src,__tests__}/**/*.ts']],
  [bin('tsc'), []],
  [bin('vitest'), ['run']]
];

const manualSection = (manual) =>
  !manual.length
    ? ''
    : `\n## Hand-written entries needed\n\nNo naming rule covers these, so a human adds them by hand.\n\`ACTIVITIES.indexOf\` is the hiscores \`table=\` parameter, so the position is part of the\nchange — an entry inserted here shifts every boss after it.\n\n${manual
        .map(
          ({ name, key, position }) =>
            `- [ ] \`${name}\` is entry ${position + 1} of \`ACTIVITIES\` in \`src/utils/constants.ts\`:\n\n  \`\`\`ts\n    '${key}',\n  \`\`\`\n\n  and its display name, if the package should expose it:\n\n  \`\`\`ts\n  export const FORMATTED_${key.replace(/[A-Z]/g, (c) => `_${c}`).toUpperCase()} = '${name}';\n  \`\`\`\n`
        )
        .join('\n')}`;

export const prBody = (title, notes, manual = []) =>
  `Automated hiscores content update: ${title}

${
  notes.length
    ? `Verify before merging:\n${notes.map((note) => `- ${note}`).join('\n')}\n`
    : ''
}${manualSection(manual)}
- [ ] Spelling matches the in-game hiscores page — a typo becomes permanent public API
- [ ] Keys read naturally against src/utils/generated/
- [ ] README boss table rows are correct
- [ ] Merge as a minor release

The lint/build/test gate ran in the job that opened this PR. A pull_request workflow
will not run on it — GitHub does not trigger workflows for PRs opened with
GITHUB_TOKEN — so treat that gate as the CI result.

Generated by \`scripts/codegen-content-pr.mjs\` from the live hiscores endpoint.`;

export const issueBody = (manual) =>
  `The hiscores list entries the package does not have, and no naming rule covers them, so\nthey need a hand-written key. Nothing else changed, so there is nothing to open a PR for.\n${manualSection(manual)}
Generated by \`scripts/codegen-content-pr.mjs\` from the live hiscores endpoint.`;

export async function codegen({ dry = false } = {}) {
  const { addedNames, notes, manual, stale } = await regen();
  const manualNames = manual.map(({ name }) => name);

  if (!stale && !manual.length) {
    console.log(
      'nothing to do — generated content already matches the hiscores'
    );
    return;
  }

  if (!stale) {
    // Nothing to commit, so a PR is impossible: the issue is the artifact.
    const title = `chore: add ${manualNames.join(', ')} to ACTIVITIES by hand`;
    if (dry) {
      console.log(`\nwould open an issue: ${title}\n`);
      console.log(issueBody(manual));
      return;
    }
    const openTitles = JSON.parse(
      read('gh', [
        'issue',
        'list',
        '--state',
        'open',
        '--limit',
        '200',
        '--json',
        'title'
      ])
    ).map(({ title: existing }) => existing);
    if (openTitles.includes(title)) {
      console.log(`issue already open: ${title}`);
      return;
    }
    run('gh', [
      'issue',
      'create',
      '--title',
      title,
      '--body',
      issueBody(manual)
    ]);
    return;
  }

  const title = addedNames.length
    ? `feat: add ${addedNames.join(', ')}`
    : 'chore: regenerate hiscores content';
  const addedKeys = addedNames.map(keyOf).join('-').slice(0, 60);
  const branch = `content/add-${addedKeys || 'regen'}`;

  if (dry) {
    console.log(`\nbranch: ${branch}\ntitle:  ${title}\n`);
    notes.forEach((note) => console.log(`note: ${note}`));
    console.log('\n--- diff ---');
    // --intent-to-add so generated files show in the diff before their first commit.
    run('git', ['add', '-N', '--', ...GENERATED_FILES]);
    run('git', ['--no-pager', 'diff', '--', ...GENERATED_FILES]);
    console.log('\n--- PR body ---\n');
    console.log(prBody(title, notes, manual));
    return;
  }

  GATE.forEach(([file, args]) => run(file, args));

  run('git', ['switch', '-C', branch]);
  run('git', ['add', ...GENERATED_FILES]);
  run('git', ['commit', '-m', title]);
  // The branch is regenerated from the default branch on every run, so a second
  // dispatch has to replace whatever the first one pushed.
  run('git', ['push', '--force', '-u', 'origin', 'HEAD']);

  const open = read('gh', [
    'pr',
    'list',
    '--head',
    branch,
    '--state',
    'open',
    '--json',
    'number',
    '--jq',
    'length'
  ]);
  if (open.trim() === '0') {
    run('gh', [
      'pr',
      'create',
      '--draft',
      '--title',
      title,
      '--body',
      prBody(title, notes, manual)
    ]);
  } else {
    console.log(`draft PR for ${branch} is already open — pushed the update`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await codegen({ dry: process.argv.includes('--dry') });
}
